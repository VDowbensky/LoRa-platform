void SSD1306_Display_On(void)
{
	SSD1306_WriteCommand(0X8D);  //SET DCDC Command
	SSD1306_WriteCommand(0X14);  //DCDC ON
	SSD1306_WriteCommand(0XAF);  //DISPLAY ON
}

void SSD1306_Display_Off(void)
{
	SSD1306_WriteCommand(0X8D);  //SET DCDC Command
	SSD1306_WriteCommand(0X10);  //DCDC OFF
	SSD1306_WriteCommand(0XAE);  //DISPLAY OFF
}

void SSD1306_Set_Pos(uint8_t x, uint8_t y)
{
 	SSD1306_WriteCommand(YLevel+y/PAGE_SIZE);
	SSD1306_WriteCommand((((x+2)&0xf0)>>4)|0x10);
	SSD1306_WriteCommand(((x+2)&0x0f)); 
}

static const uint8_t init[] =
{
	0xAE,       // Display OFF
	0xD5, 0x80, // Clock
	0xA8, 0x3F, // Multiplex
	0xD3, 0x00, // Offset
	0x40,       // Start line
	0x8D, 0x14, // Charge pump
	0x20, 0x00, // Horizontal addressing
	0xA1,       // Segment remap
	0xC8,       // COM scan direction
	0xDA, 0x12, // COM pins
	0x81, 0xCF, // Contrast
	0xD9, 0xF1, // Precharge
	0xDB, 0x40, // VCOMH
	0xA4,       // Resume RAM
	0xA6,       // Normal display
	0x2E,       // Stop scroll
	0xAF        // Display ON
};

void SSD1306_Init(void)
{
 	SSD1306_interface_init();
 	delay_ms(10);
	for(uint32_t i=0;i<sizeof(init);i++) SSD1306_WriteCommand(init[i]);
}

void SSD1306_Set_Pixel(uint8_t x, uint8_t y,uint8_t color)
{
	if(color) SSD1306_buffer[(y/PAGE_SIZE)*WIDTH+x]|= (1<<(y%PAGE_SIZE))&0xff;
	else SSD1306_buffer[(y/PAGE_SIZE)*WIDTH+x]&= ~((1<<(y%PAGE_SIZE))&0xff);
}

void SSD1306_Display(void)
{
	uint8_t i,n;		    
	for(i=0;i<PAGE_SIZE;i++)  
	{  
		SSD1306_WriteCommand (YLevel+i);    //Set page address (0~7)
		SSD1306_WriteCommand (XLevelL);     //Set the display position - column low address
		SSD1306_WriteCommand (XLevelH);     //Set display position - column high address  
		//Update Display
		SSD1306_WriteData(&SSD1306_buffer[i*128],128); 
	}   
}

void SSD1306_Clear(uint8_t dat)
{
	if(dat) memset(SSD1306_buffer,0xff,sizeof(SSD1306_buffer));
	else memset(SSD1306_buffer,0,sizeof(SSD1306_buffer));
	SSD1306_Display();
}
